import { core } from '../lib.mjs';
const turn = await core('turn'), room = await core('room'), et = await core('endturn');
let base = turn.newJourney(4127, 'normal');
const open = (x, y) => !room.tileAt(base.room, x, y).solid && !base.items.some(i => i.x === x && i.y === y);
let h = null;
for (let y = 2; y < base.room.rows - 2 && !h; y++) for (let x = 2; x < base.room.cols - 6 && !h; x++) if ([0,1,2,3,4].every(d => open(x + d, y) && open(x + d, y - 1))) h = { x, y };
base = { ...base, hero: h, enemies: [], health: 5 };
console.log('hero', h);
const show = (s, tag) => console.log(tag.padEnd(22), 'hp', s.health, '|', (s.line?.turn === s.turn ? (s.line?.text ?? s.line?.id) : '-'), '|', JSON.stringify(s.enemies.map(e => ({ id: e.id, x: e.x - h.x, y: e.y - h.y, hp: e.health, raised: e.raised && 1, rests: e.rests, asleep: e.asleep, awake: e.awake, stirs: e.stirs }))), 'hero', s.hero.x - h.x, s.hero.y - h.y);
let s = { ...base, enemies: [{ id: 'scorpion', x: h.x + 4, y: h.y, chasing: true }] };
s = et.wait(s); show(s, 'sc wait1');
s = et.wait(s); show(s, 'sc wait2');
s = turn.step(s, 'up'); show(s, 'sc step aside');
s = turn.step(s, 'right'); show(s, 'sc toward');
s = turn.step(s, 'down'); show(s, 'sc next');
s = turn.step(s, 'right'); show(s, 'sc next2');
s = { ...base, enemies: [{ id: 'herbMimic', x: h.x + 1, y: h.y, asleep: true }] };
s = turn.step(s, 'right'); show(s, 'bump mimic');
s = turn.step(s, 'right'); show(s, 'strike 1');
s = turn.step(s, 'right'); show(s, 'strike 2');
s = { ...base, enemies: [{ id: 'snapcap', x: h.x + 2, y: h.y }] };
s = turn.step(s, 'right'); show(s, 'beside snapcap');
s = { ...base, enemies: [{ id: 'lureWisp', x: h.x + 2, y: h.y }] };
s = et.wait(s); show(s, 'wisp alone');
s = { ...base, enemies: [{ id: 'rimLurker', x: h.x + 3, y: h.y }] };
s = et.wait(s); show(s, 'lurker 3 away');
